use anyhow::Result;
use colored::Colorize;
use std::path::{Path, PathBuf};

/// First line of generated ignore files; Drop and `l8b cleanup` only remove files carrying it.
pub(crate) const GENERATED_MARKER: &str = "# generated by l8b";

/// Whether the file is an ignore file l8b itself generated (marker intact).
fn is_l8b_generated(path: &Path) -> bool {
    std::fs::read_to_string(path).ok().is_some_and(|c| c.lines().next().is_some_and(|l| l.trim() == GENERATED_MARKER))
}

/// Manages the generated `<Dockerfile>.dockerignore`; no other file is read, written, or deleted.
pub struct BuildContextGuard {
    ignore_path: Option<PathBuf>,
}

impl BuildContextGuard {
    pub fn new(project_dir: &Path, dockerfile_name: &str, env_files: &[PathBuf], ci_mode: bool) -> Result<Self> {
        let dockerfile_basename = Path::new(dockerfile_name).file_name().unwrap_or_default().to_string_lossy();
        let target_ignore = project_dir.join(format!("{}.dockerignore", dockerfile_basename));

        // A user-authored ignore file wins; a marked leftover from an interrupted build is ours to replace.
        if target_ignore.exists() && !is_l8b_generated(&target_ignore) {
            if !ci_mode {
                println!("  {} Using your existing {}.dockerignore", "::".dimmed(), dockerfile_basename);
            }
            return Ok(Self { ignore_path: None });
        }

        // Base content comes from .dockerignore if present, else .gitignore.
        let mut base_ignore = String::new();
        let existing_ignore = project_dir.join(".dockerignore");
        let gitignore = project_dir.join(".gitignore");
        if existing_ignore.exists() {
            base_ignore = std::fs::read_to_string(&existing_ignore)?;
        } else if gitignore.exists() {
            base_ignore = std::fs::read_to_string(&gitignore)?;
        }

        // Negations re-include exactly the selected env files in the context dir; must follow the base rules.
        let mut negations: Vec<String> = Vec::new();
        for file in env_files {
            let inside_ctx = file.parent() == Some(project_dir);
            match (file.file_name(), inside_ctx) {
                (Some(name), true) => negations.push(format!("!{}", name.to_string_lossy())),
                _ if !ci_mode => println!(
                    "  {} {} is outside the build context — Dockerfile builds cannot include it",
                    "!".yellow(),
                    file.display()
                ),
                _ => {}
            }
        }
        negations.sort();
        negations.dedup();

        if base_ignore.trim().is_empty() && negations.is_empty() {
            return Ok(Self { ignore_path: None });
        }

        let mut content = format!("{}\n", GENERATED_MARKER);
        if !base_ignore.trim().is_empty() {
            content.push_str(base_ignore.trim_end());
            content.push('\n');
        }
        for n in &negations {
            content.push_str(n);
            content.push('\n');
        }

        std::fs::write(&target_ignore, &content)?;
        Ok(Self { ignore_path: Some(target_ignore) })
    }
}

impl Drop for BuildContextGuard {
    fn drop(&mut self) {
        let Some(path) = &self.ignore_path else { return };
        if !is_l8b_generated(path) {
            return; // marker gone — the file is no longer ours, leave it
        }
        if let Err(e) = std::fs::remove_file(path) {
            eprintln!("  {} Could not remove {}: {} — run `l8b cleanup`", "!".yellow(), path.display(), e);
        }
    }
}

/// Remove leftover build artifacts from interrupted builds: l8b-generated
/// `<Dockerfile>.dockerignore` files (marked files only).
pub fn cleanup_build_artifacts(dir: &Path) -> Result<()> {
    let mut cleaned = 0usize;
    let mut skipped = 0usize;

    // Remove l8b-generated dockerignore files
    let dockerignores: Vec<_> = std::fs::read_dir(dir)?
        .filter_map(|e| e.ok())
        .filter(|e| {
            let name = e.file_name();
            let name_str = name.to_string_lossy();
            name_str.ends_with(".dockerignore") && name_str != ".dockerignore"
        })
        .collect();

    for entry in &dockerignores {
        let path = entry.path();
        let name = path.file_name().unwrap_or_default().to_string_lossy();
        if !is_l8b_generated(&path) {
            println!("    {} {} — not generated by l8b, skipping", "!".yellow(), name);
            skipped += 1;
            continue;
        }
        match std::fs::remove_file(&path) {
            Ok(()) => {
                println!("    {} Removed {}", "✔".green(), name);
                cleaned += 1;
            }
            Err(e) => {
                println!("    {} Failed to remove {}: {}", "✗".red(), name, e);
                skipped += 1;
            }
        }
    }

    if cleaned == 0 && skipped == 0 {
        println!("  No build artifacts found. Directory is clean.");
    } else {
        println!();
        println!("  Cleaned: {}, Skipped: {}", cleaned.to_string().green(), skipped);
    }

    Ok(())
}

/// Return directory names to mask in the Docker build context on Windows.
/// Reads `.dockerignore` if present, otherwise falls back to `.gitignore`.
/// Only returns top-level directory names that actually exist on disk.
pub(crate) fn gitignored_dirs(project_dir: &Path) -> Vec<String> {
    let mut dirs = std::collections::HashSet::new();

    // Always try to mask these common suspects if they exist
    let defaults = vec![".git", "node_modules", ".next", ".vercel", "build", "dist", "target"];
    for d in defaults {
        if project_dir.join(d).is_dir() {
            dirs.insert(d.to_string());
        }
    }

    let ignore_file = if project_dir.join(".dockerignore").exists() {
        project_dir.join(".dockerignore")
    } else {
        project_dir.join(".gitignore")
    };

    if let Ok(content) = std::fs::read_to_string(&ignore_file) {
        for line in content.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') || line.starts_with('!') {
                continue;
            }

            // Clean the pattern
            let pattern = line.trim_start_matches('/');

            // On Windows, we can only reliably mask top-level directories via --tmpfs.
            // If the pattern is complex (has * or / in the middle), we skip it
            // and let the internal .dockerignore handle it.

            // Simple directory name (e.g. "node_modules" or ".next/")
            let clean_pattern = pattern.trim_end_matches('/');
            if !clean_pattern.contains('/') && !clean_pattern.contains('*') && project_dir.join(clean_pattern).is_dir()
            {
                dirs.insert(clean_pattern.to_string());
            }
        }
    }

    dirs.into_iter().collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("l8b-ctx-{}-{}", name, std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn dotenv_files(dir: &Path, names: &[&str]) -> Vec<PathBuf> {
        names.iter().map(|n| dir.join(n)).collect()
    }

    #[test]
    fn no_env_selected_leaves_user_dotenv_untouched() {
        let dir = temp_dir("no-env");
        std::fs::write(dir.join(".env"), "SECRET=1\n").unwrap();
        std::fs::write(dir.join(".gitignore"), "node_modules\n.env\n").unwrap();

        let guard = BuildContextGuard::new(&dir, "Dockerfile", &[], true).unwrap();
        assert_eq!(std::fs::read_to_string(dir.join(".env")).unwrap(), "SECRET=1\n");
        drop(guard);
        assert_eq!(std::fs::read_to_string(dir.join(".env")).unwrap(), "SECRET=1\n");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn generated_ignore_has_marker_base_and_negations_then_removed() {
        let dir = temp_dir("generated");
        std::fs::write(dir.join(".gitignore"), "node_modules\n.env\n").unwrap();
        std::fs::write(dir.join(".env"), "A=1\n").unwrap();
        std::fs::write(dir.join(".env.local"), "B=2\n").unwrap();

        let guard =
            BuildContextGuard::new(&dir, "Dockerfile", &dotenv_files(&dir, &[".env", ".env.local"]), true).unwrap();
        let ignore_file = dir.join("Dockerfile.dockerignore");
        let content = std::fs::read_to_string(&ignore_file).unwrap();
        assert_eq!(content.lines().next().unwrap(), GENERATED_MARKER);
        assert!(content.contains("node_modules"));
        assert!(content.contains("!.env"));
        assert!(content.contains("!.env.local"));

        drop(guard);
        assert!(!ignore_file.exists());
        assert_eq!(std::fs::read_to_string(dir.join(".env")).unwrap(), "A=1\n");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn user_authored_ignore_is_respected() {
        let dir = temp_dir("user-ignore");
        std::fs::write(dir.join("Dockerfile.dockerignore"), "*\n!src\n").unwrap();
        std::fs::write(dir.join(".env"), "A=1\n").unwrap();

        let guard = BuildContextGuard::new(&dir, "Dockerfile", &dotenv_files(&dir, &[".env"]), true).unwrap();
        assert_eq!(std::fs::read_to_string(dir.join("Dockerfile.dockerignore")).unwrap(), "*\n!src\n");
        drop(guard);
        assert_eq!(std::fs::read_to_string(dir.join("Dockerfile.dockerignore")).unwrap(), "*\n!src\n");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn marker_leftover_ignore_is_replaced() {
        let dir = temp_dir("leftover");
        std::fs::write(dir.join(".gitignore"), "node_modules\n").unwrap();
        std::fs::write(dir.join(".env"), "A=1\n").unwrap();
        // stale leftover from an interrupted build (marked, wrong negations)
        std::fs::write(dir.join("Dockerfile.dockerignore"), format!("{}\nnode_modules\n!.env.old\n", GENERATED_MARKER))
            .unwrap();

        let guard = BuildContextGuard::new(&dir, "Dockerfile", &dotenv_files(&dir, &[".env"]), true).unwrap();
        let content = std::fs::read_to_string(dir.join("Dockerfile.dockerignore")).unwrap();
        assert!(content.contains("!.env"));
        assert!(!content.contains("!.env.old"));
        drop(guard);
        assert!(!dir.join("Dockerfile.dockerignore").exists());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn drop_spares_ignore_without_marker() {
        let dir = temp_dir("spare");
        std::fs::write(dir.join(".gitignore"), "node_modules\n").unwrap();
        let guard = BuildContextGuard::new(&dir, "Dockerfile", &[], true).unwrap();
        let ignore_file = dir.join("Dockerfile.dockerignore");
        std::fs::write(&ignore_file, "user rewrote it\n").unwrap();
        drop(guard);
        assert_eq!(std::fs::read_to_string(&ignore_file).unwrap(), "user rewrote it\n");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn no_ignore_file_when_no_base_and_no_env() {
        let dir = temp_dir("bare");
        let guard = BuildContextGuard::new(&dir, "Dockerfile", &[], true).unwrap();
        assert!(!dir.join("Dockerfile.dockerignore").exists());
        drop(guard);
        assert!(!dir.join("Dockerfile.dockerignore").exists());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn cleanup_removes_only_marked_ignores() {
        let dir = temp_dir("cleanup");
        std::fs::write(dir.join("Dockerfile.dockerignore"), format!("{}\nnode_modules\n", GENERATED_MARKER)).unwrap();
        std::fs::write(dir.join("Api.Dockerfile.dockerignore"), "custom rules\n").unwrap();

        cleanup_build_artifacts(&dir).unwrap();
        assert!(!dir.join("Dockerfile.dockerignore").exists());
        assert!(dir.join("Api.Dockerfile.dockerignore").exists());
        let _ = std::fs::remove_dir_all(&dir);
    }
}
