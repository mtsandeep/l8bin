#!/usr/bin/env python3
"""Generate REPORT.md + report.html from run directories and k6 JSONs.

Usage: python3 report.py            (from test-apps/resource-stress/)
New runs: drop the observer output in a directory and add it to RUNS below
(or leave it out — unknown directories with a probe.log are included
automatically, labeled by directory name).
"""
import glob
import html
import json
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

RUNS = {
    "baseline": ("Baseline — unprotected, 480MB hogs", "protection OFF · swap 2.3G"),
    "protected": ("Protected — 480MB hogs", "protection ON · swap 2.3G"),
    "swap1g": ("Protected — 1× swap, 480MB hogs", "protection ON · swap 1G"),
    "unprotected-1g": ("Unprotected — 1× swap, 480MB hogs", "protection OFF · swap 1G"),
    "unprot-2g3": ("Unprotected — 5 hogs, k6 window", "protection OFF · swap 2.25G"),
}
# Raw data only, excluded from the summary: this observer ran through several
# phases back-to-back (aborted 40MB fleet, CPU storm, cleanups), so whole-run
# aggregates for it are meaningless. See RESULTS.md phase notes instead.
EXCLUDE = {"prot-2g3-small"}
K6 = {
    "unprotected-1g-k6.json": "protection OFF · swap 1G",
    "protected-1g-k6.json": "protection ON · swap 1G",
    "unprot-2g3-k6.json": "protection OFF · swap 2.3G",
    "prot-2g3-k6.json": "protection ON · swap 2.3G",
}


def percentile(sorted_vals, p):
    if not sorted_vals:
        return None
    i = min(len(sorted_vals) - 1, max(0, round(p / 100 * len(sorted_vals)) - 1))
    return sorted_vals[i]


def parse_probe(path):
    if not os.path.exists(path):
        return None
    lats, bad = [], 0
    with open(path) as f:
        for line in f:
            parts = line.split()
            if len(parts) < 3 or not parts[1].lstrip("-").isdigit():
                continue
            if parts[1] != "200":
                bad += 1
            try:
                lats.append(float(parts[2]))
            except ValueError:
                continue
    if not lats:
        return None
    s = sorted(lats)
    n = len(s)
    return {
        "n": n,
        "avg": sum(s) / n,
        "p50": percentile(s, 50),
        "p95": percentile(s, 95),
        "max": s[-1],
        "ge2": 100 * sum(1 for x in s if x >= 2) // n,
        "non200": bad,
    }


def parse_events(path):
    if not os.path.exists(path):
        return None
    kills, deploys, outages = [], 0, 0
    with open(path) as f:
        for line in f:
            if "-> stopped" in line:
                kills.append(line.strip())
            elif "-> running" in line:
                deploys += 1
            elif "API unreachable" in line:
                outages += 1
    return {"kills": kills, "deploys": deploys, "outages": outages}


def parse_stats_peak(path):
    if not os.path.exists(path):
        return None
    peak, current = 0, 0
    last_t = None
    with open(path) as f:
        for line in f:
            parts = line.split(",")
            if len(parts) < 4:
                continue
            t = parts[0]
            if t != last_t:
                peak, current, last_t = max(peak, current), 0, t
            if parts[3] == "running" and parts[1].startswith(("stress", "cpu-", "mem-", "canary", "final")):
                current += 1
    return max(peak, current)


def fmt(v, suffix="s", nd=2):
    return f"{v:.{nd}f}{suffix}" if v is not None else "—"


def load_runs():
    runs = []
    names = list(RUNS)
    for d in sorted(glob.glob(os.path.join(HERE, "runs", "*/"))):
        name = os.path.basename(d.rstrip("/\\"))
        if name in EXCLUDE or not os.path.exists(os.path.join(d, "probe.log")):
            continue
        title, config = RUNS.get(name, (name, ""))
        probe = parse_probe(os.path.join(d, "probe.log"))
        api = parse_probe(os.path.join(d, "api-probe.log"))
        ev = parse_events(os.path.join(d, "events.log"))
        runs.append({
            "name": name, "title": title, "config": config, "probe": probe, "api": api, "ev": ev,
            "peak": parse_stats_peak(os.path.join(d, "stats.csv")),
        })
    return runs


def load_k6():
    rows = []
    for fname, config in K6.items():
        path = os.path.join(HERE, "runs", fname)
        if not os.path.exists(path):
            continue
        d = json.load(open(path))
        for route in ("root", "api"):
            m = d["metrics"].get(f"http_req_duration{{route:{route}}}")
            if m and "med" in m:
                rows.append({"config": config, "route": route, "med": m["med"], "p90": m["p(90)"],
                             "p95": m["p(95)"], "max": m["max"]})
    return rows


def build_md(runs, k6rows):
    out = ["# Resource-stress report", "",
           "Generated by `report.py` from the raw run data in this directory. Narrative and methodology: [RESULTS.md](RESULTS.md).", "",
           "`stops` counts every container →stopped transition (OOM kills **and** deliberate cleanup deletes and janitor idle-stops — not distinguishable in events.log; the OOM kills are identified in RESULTS.md). `api outages` includes observer-side TLS failures — treat small counts with suspicion.", "",
           "## Run summary", "",
           "| run | config | peak apps | stops | probe avg / p95 / max | ≥2s | api avg / p95 / max | api outages |",
           "|---|---|---|---|---|---|---|---|"]
    for r in runs:
        p, a, ev = r["probe"], r["api"], r["ev"] or {}
        kills = len(ev.get("kills", []))
        probe_s = f"{fmt(p['avg'])} / {fmt(p['p95'])} / {fmt(p['max'], nd=1)}" if p else "—"
        api_s = f"{fmt(a['avg'])} / {fmt(a['p95'])} / {fmt(a['max'], nd=1)}" if a else "—"
        out.append(f"| {r['title']} | {r['config']} | {r['peak'] if r['peak'] else '—'} | {kills} | {probe_s} | {fmt_val(p and p['ge2'], '%')} | {api_s} | {ev.get('outages', '—')} |")
    out += ["", "## k6 percentiles (2-min windows, keep-alive)", "",
            "| config | route | med | p90 | p95 | max |", "|---|---|---|---|---|---|"]
    for k in k6rows:
        out.append(f"| {k['config']} | {k['route']} | {fmt(k['med'], 'ms', 0)} | {fmt(k['p90'], 'ms', 0)} | {fmt(k['p95'], 'ms', 0)} | {fmt(k['max'], 'ms', 0)} |")
    return "\n".join(out) + "\n"


def fmt_val(v, suffix=""):
    return f"{v}{suffix}" if v is not None else "—"


def build_html(md_tables):
    body = md_tables.replace("&", "&amp;").replace("<", "&lt;")
    # crude markdown-table -> html conversion (only tables + headings needed)
    import re
    lines, out, in_table = body.splitlines(), [], False
    for ln in lines:
        if ln.startswith("|"):
            cells = [c.strip() for c in ln.strip("|").split("|")]
            if all(re.fullmatch(r"-+", c) for c in cells):
                continue
            tag = "th" if not in_table else "td"
            out.append("<tr>" + "".join(f"<{tag}>{html.escape(c)}</{tag}>" for c in cells) + "</tr>")
            in_table = True
            continue
        if in_table:
            out.append("</table>")
            in_table = False
        if ln.startswith("# "):
            out.append(f"<h1>{html.escape(ln[2:])}</h1>")
        elif ln.startswith("## "):
            out.append("<table>" if False else f"<h2>{html.escape(ln[3:])}</h2>")
            out.append("<table>")
        elif ln.startswith("- "):
            out.append(f"<li>{html.escape(ln[2:])}</li>")
        elif ln.strip():
            out.append(f"<p>{html.escape(ln)}</p>")
    if in_table:
        out.append("</table>")
    return ("<!doctype html><html><head><meta charset='utf-8'><title>LiteBin resource-stress report</title>"
            "<style>body{font-family:system-ui,sans-serif;margin:2rem;color:#222}"
            "table{border-collapse:collapse;margin:1rem 0 1.5rem}td,th{border:1px solid #ccc;padding:4px 10px;font-size:14px;text-align:left}"
            "th{background:#f5f5f5}h1{font-size:22px}h2{font-size:17px;margin-top:2rem}li{font-family:monospace;font-size:13px}</style>"
            "</head><body>" + "".join(out) + "</body></html>")


def main():
    runs = load_runs()
    k6rows = load_k6()
    md = build_md(runs, k6rows)
    open(os.path.join(HERE, "REPORT.md"), "w").write(md)
    open(os.path.join(HERE, "report.html"), "w").write(build_html(md))
    print(md)
    print(f"wrote REPORT.md and report.html from {len(runs)} runs, {len(k6rows)} k6 rows")


if __name__ == "__main__":
    main()
